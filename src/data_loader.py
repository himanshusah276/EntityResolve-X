# VERIFICATION & DIAGNOSTICS
# =====================================================================

def verify_candidate_pairs(
    candidates_df: pd.DataFrame,
    s1_df: Optional[pd.DataFrame] = None,
    targets_df: Optional[pd.DataFrame] = None,
) -> Dict[str, Union[int, float, bool]]:
    """
    Verifies that:
    1. Candidate IDs come ONLY from Source 2 or Source 3 (start with 'S2-' or 'S3-')
    2. Source 1 IDs start with 'S1-'
    3. All candidate pairs can be joined back to source records (if provided)
    4. Diagnostics: candidate ratio, entity coverage

    Returns:
        Dictionary of verification metrics.
    """
    total_pairs = len(candidates_df)
    if total_pairs == 0:
        return {"total_pairs": 0, "is_valid": False}

    s1_ids = candidates_df["source1_entity_id"].astype(str)
    cand_ids = candidates_df["candidate_entity_id"].astype(str)

    # Check ID prefix constraints
    valid_s1_prefixes = s1_ids.str.startswith("S1-").all()
    valid_cand_prefixes = cand_ids.str.startswith("S2-") | cand_ids.str.startswith("S3-")
    valid_cand_all = valid_cand_prefixes.all()

    s2_count = cand_ids.str.startswith("S2-").sum()
    s3_count = cand_ids.str.startswith("S3-").sum()
    invalid_cand_count = (~valid_cand_prefixes).sum()

    metrics: Dict[str, Union[int, float, bool]] = {
        "total_candidate_pairs": int(total_pairs),
        "unique_source1_entities": int(s1_ids.nunique()),
        "unique_candidate_entities": int(cand_ids.nunique()),
        "s2_candidates_count": int(s2_count),
        "s3_candidates_count": int(s3_count),
        "invalid_candidate_id_count": int(invalid_cand_count),
        "all_s1_ids_valid": bool(valid_s1_prefixes),
        "all_candidate_ids_valid": bool(valid_cand_all),
    }

    # Verify joins back to source records if provided
    if s1_df is not None:
        known_s1 = set(s1_df["entity_id"])
        cand_s1_in_known = s1_ids.isin(known_s1).mean()
        metrics["source1_join_rate"] = float(cand_s1_in_known)

    if targets_df is not None:
        known_targets = set(targets_df["entity_id"])
        cand_in_known = cand_ids.isin(known_targets).mean()
        metrics["target_join_rate"] = float(cand_in_known)

    metrics["is_valid"] = bool(valid_s1_prefixes and valid_cand_all)
    return metrics


def compute_candidate_recall(
    candidates_df: pd.DataFrame,
    gt_dict: Dict[str, Set[str]],
    evaluated_s1_ids: Optional[Set[str]] = None,
) -> Dict[str, Union[int, float]]:
    """
    Computes Stage-1 Candidate Recall:
    Candidate Recall = (True matches found in candidate set) / (Total true matches in Ground Truth)
    """
    if evaluated_s1_ids is None:
        evaluated_s1_ids = set(candidates_df["source1_entity_id"])

    # Group candidate set by S1 ID
    candidate_map: Dict[str, Set[str]] = {}
    for row in candidates_df.itertuples(index=False):
        s1 = row.source1_entity_id
        cand = row.candidate_entity_id
        if s1 not in candidate_map:
            candidate_map[s1] = set()
        candidate_map[s1].add(cand)

    total_true_pairs = 0
    found_true_pairs = 0

    for s1_id in evaluated_s1_ids:
        true_matches = gt_dict.get(s1_id, set())
        total_true_pairs += len(true_matches)
        cands = candidate_map.get(s1_id, set())
        found_true_pairs += len(true_matches & cands)

    recall = (found_true_pairs / total_true_pairs) if total_true_pairs > 0 else 0.0

    return {
        "candidate_recall": float(recall),
        "found_true_pairs": int(found_true_pairs),
        "total_true_pairs": int(total_true_pairs),
        "evaluated_s1_count": int(len(evaluated_s1_ids)),
    }


