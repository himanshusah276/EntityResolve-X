def load_candidate_pairs(
    candidate_path: Optional[Union[str, Path]] = None,
    nrows: Optional[int] = None,
    filter_s1_ids: Optional[Set[str]] = None,
) -> pd.DataFrame:
    """
    Loads Person 1's candidate pairs.

    Adapts flexibly to either:
    1. Pair format:
       columns = ['source1_entity_id', 'candidate_entity_id']
    2. Comma-separated list format (from Person 1's main.py):
       columns = ['source1_entity_id', 'candidate_entity_ids']
       which is automatically exploded into pair format.

    Returns:
        pd.DataFrame with columns: ['source1_entity_id', 'candidate_entity_id']
    """
    target_path = None
    if candidate_path:
        target_path = Path(candidate_path)
    else:
        existing = locate_candidate_files()
        if existing:
            target_path = existing[0]

    if target_path and target_path.exists():
        print(f"[DataLoader] Loading candidate pairs from existing file: {target_path}")
        if target_path.suffix == ".parquet":
            df = pd.read_parquet(target_path)
        else:
            df = pd.read_csv(target_path, sep="\t", nrows=nrows, dtype=str)

        # Handle Person 1's list format if present
        if "candidate_entity_ids" in df.columns and "candidate_entity_id" not in df.columns:
            print("[DataLoader] Detected Person 1 list format ('candidate_entity_ids'). Exploding to pairs...")
            df["candidate_entity_id"] = df["candidate_entity_ids"].fillna("").astype(str).str.split(",")
            df = df.explode("candidate_entity_id").reset_index(drop=True)
            df = df[df["candidate_entity_id"].str.strip() != ""]

        # Ensure correct column names
        required_cols = ["source1_entity_id", "candidate_entity_id"]
        for c in required_cols:
            if c not in df.columns:
                raise ValueError(f"Candidate file missing required column '{c}'. Available: {df.columns.tolist()}")

        df = df[required_cols].drop_duplicates()

        if filter_s1_ids is not None:
            df = df[df["source1_entity_id"].isin(filter_s1_ids)].copy()

        return df

    # If no candidate file exists on disk yet, raise informative error or provide guidance
    raise FileNotFoundError(
        "[DataLoader] No candidate pairs file found on disk. "
        "Expected one of:\n" + "\n".join(str(p) for p in [
            DEFAULT_DATA_DIR / "candidate_pairs.parquet",
            DEFAULT_DATA_DIR / "candidate_pairs.tsv",
            DEFAULT_OUTPUT_DIR / "candidate_pairs.tsv",
            FALLBACK_PERSON1_OUTPUT / "candidate_pairs.tsv"
        ])
    )


def generate_sample_candidate_pairs(
    s1_df: pd.DataFrame,
    s2_df: pd.DataFrame,
    s3_df: pd.DataFrame,
    gt_dict: Dict[str, Set[str]],
    negative_sample_ratio: int = 5,
    random_seed: int = 42,
) -> pd.DataFrame:
    """
    Development fallback helper:
    If Person 1 has not saved candidate_pairs.tsv to disk, this constructs
    a valid candidate set for development/testing:
    - True positive pairs from Ground Truth (matching Person 1's target candidate recall)
    - Sample negative candidates from S2 and S3 for each S1 entity

    Returns:
        pd.DataFrame with ['source1_entity_id', 'candidate_entity_id']
    """
    rng = np.random.default_rng(random_seed)
    all_target_ids = np.concatenate([
        s2_df["entity_id"].values,
        s3_df["entity_id"].values
    ])

    pairs = []
    for s1_id in s1_df["entity_id"]:
        positives = gt_dict.get(s1_id, set())
        for pos_id in positives:
            pairs.append({"source1_entity_id": s1_id, "candidate_entity_id": pos_id})

        # Add random negative candidates from S2/S3
        num_neg = max(negative_sample_ratio, negative_sample_ratio * len(positives))
        if len(all_target_ids) > 0:
            negs = rng.choice(all_target_ids, size=min(num_neg, len(all_target_ids)), replace=False)
            for neg_id in negs:
                if neg_id not in positives:
                    pairs.append({"source1_entity_id": s1_id, "candidate_entity_id": neg_id})

    candidates_df = pd.DataFrame(pairs).drop_duplicates().reset_index(drop=True)
    return candidates_df


