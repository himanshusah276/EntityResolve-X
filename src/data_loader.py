def load_source_record(
    source_num: int,
    split: str = "train",
    nrows: Optional[int] = None,
    usecols: Optional[List[str]] = None,
) -> pd.DataFrame:
    """
    Loads records for Source 1, 2, or 3.

    Args:
        source_num: 1, 2, or 3
        split: 'train' or 'test'
        nrows: number of rows to load (None for all rows)
        usecols: subset of columns to load for memory efficiency

    Returns:
        pd.DataFrame with columns ['entity_id', 'business_name', 'business_address', 'country']
    """
    filename = f"{split}_source{source_num}.tsv"
    file_path = resolve_data_path(split, filename)

    if not file_path.exists():
        raise FileNotFoundError(f"Source file not found at: {file_path}")

    # Enforce competition requirement: TSV loaded with sep="\t"
    df = pd.read_csv(
        file_path,
        sep="\t",
        nrows=nrows,
        usecols=usecols,
        dtype={"entity_id": str, "business_name": str, "business_address": str, "country": str},
        keep_default_na=False,
    )

    # Standardize string fields
    for col in ["business_name", "business_address", "country"]:
        if col in df.columns:
            df[col] = df[col].fillna("").astype(str).str.strip()

    return df


def load_ground_truth(
    split: str = "train",
    nrows: Optional[int] = None,
    filter_s1_ids: Optional[Set[str]] = None,
) -> pd.DataFrame:
    """
    Loads train_ground_truth.tsv.

    Args:
        split: must be 'train' as test ground truth is held out.
        nrows: number of rows to load (None for all).
        filter_s1_ids: optional set of Source 1 IDs to filter for.

    Returns:
        pd.DataFrame with ['source1_entity_id', 'matched_entity_ids']
    """
    filename = f"{split}_ground_truth.tsv"
    file_path = resolve_data_path(split, filename)

    if not file_path.exists():
        raise FileNotFoundError(f"Ground truth file not found at: {file_path}")

    gt_df = pd.read_csv(
        file_path,
        sep="\t",
        nrows=nrows,
        dtype=str,
        keep_default_na=False,
    )

    if filter_s1_ids is not None:
        gt_df = gt_df[gt_df["source1_entity_id"].isin(filter_s1_ids)].copy()

    return gt_df


def parse_ground_truth_dict(gt_df: pd.DataFrame) -> Dict[str, Set[str]]:
    """
    Parses ground truth DataFrame into mapping:
        source1_entity_id -> set of matched candidate entity_ids.
    """
    gt_dict: Dict[str, Set[str]] = {}
    for row in gt_df.itertuples(index=False):
        s1_id = str(row.source1_entity_id).strip()
        matched_str = str(row.matched_entity_ids).strip()
        if not matched_str or matched_str.lower() == "nan":
            gt_dict[s1_id] = set()
        else:
            targets = {t.strip() for t in matched_str.split(",") if t.strip()}
            gt_dict[s1_id] = targets
    return gt_dict


